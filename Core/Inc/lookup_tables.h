#define PI 3.14159265358979323
const float INCR_SIZE = PI/360.0;

float motorLinearizationLookup(float input) {
  float in_value = input;

  // Bring value to within acceptable range
  while (in_value < -PI) in_value += 2*PI;
  while (in_value >  PI) in_value -= 2*PI;

  // -pi -> 0, pi -> 720
  float lookupPoint = (in_value+PI)/INCR_SIZE;

  // Lookup indices
  uint16_t idx1 = (uint16_t)floor(lookupPoint);
  uint16_t idx2 =  (uint16_t)ceil(lookupPoint);

  // Interpolation value
  float t = lookupPoint - idx1;

  // Linear interpolation
  return (1 - t)*linearization_table[idx1] + t * linearization_table[idx2];

}

